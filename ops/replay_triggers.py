"""Replay the monitor's retune rules on 2019-2026, to check they fire when they should and stay quiet otherwise.

Runs on the public app's snapshot (public_app/data/daily.parquet), so it needs no workspace:
1. A walk-forward replay like production: every Monday from July 2019, fit the production settings on every
   earlier day and forecast the next 90 days (about 380 fits, about 7 minutes).
2. The replay scored as if it were live: its 28-day error against the band as of each month, and the dates
   the error trigger would have fired.
3. Drift by month: the model's errors and the crowd level, each against its calibrated threshold.

Writes ops/replay_results.md. `--cache` keeps the walk-forward replay in a parquet file between runs.
    python ops/replay_triggers.py [--cache replay.parquet]
"""

import argparse
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "databricks" / "src"))

from parks_lib import monitoring as mon  # noqa: E402
from parks_lib.forecast import CALENDAR_FEATURES  # noqa: E402

SNAPSHOT = ROOT / "public_app" / "data" / "daily.parquet"
OUT = ROOT / "ops" / "replay_results.md"
START = "2019-07-01"
EVENTS = {   # what was going on, for reading the results; nothing below uses it
    "2020-06": "parks reopen after the COVID closure", "2020-07": "reopening, capacity limits",
    "2020-10": "reduced-capacity fall", "2021-03": "spring 2021 recovery", "2021-06": "reopening rebound",
    "2021-07": "reopening rebound", "2021-08": "Delta wave", "2021-09": "Delta wave",
    "2022-09": "Hurricane Ian (late September)", "2025-05": "Epic Universe opens May 22",
    "2025-06": "Epic Universe's first weeks", "2025-07": "Epic Universe's first summer",
}


def table(rows, header):
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    return "\n".join(lines + ["| " + " | ".join(map(str, r)) + " |" for r in rows])


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--cache", type=Path, help="parquet file to keep the walk-forward replay in")
    args = parser.parse_args(argv)

    daily = pd.read_parquet(SNAPSHOT)
    if args.cache and args.cache.exists():
        replay = pd.read_parquet(args.cache)
    else:
        frame = daily.assign(park_id=daily["park_id"].astype("category"))
        replay = mon.walk_forward(frame, CALENDAR_FEATURES, start=START)
        if args.cache:
            replay.to_parquet(args.cache)

    accuracy = mon.accuracy_table(replay, replay)
    fires = mon.fire_dates(accuracy)
    errors = mon.error_drift(replay)
    crowd = mon.crowd_drift(daily[["park_id", "date", "crowd_percent"]])

    trig = accuracy[accuracy["bucket"] == mon.TRIGGER_HORIZON].dropna(subset=["band_high"])
    by_year = trig.groupby(trig["date"].dt.year).agg(error=("live_mae", "mean"), band=("band_high", "mean"),
                                                     above=("live_mae", "size"))
    by_year["above"] = trig.assign(a=trig["live_mae"] > trig["band_high"]).groupby(trig["date"].dt.year)["a"].mean()
    fires_by_year = pd.Series([d.year for d in fires]).value_counts()

    def flagged(t):
        f = t[t["psi"] > t["threshold"]]
        return [(f"{m:%Y-%m}", f"{p:.2f}", f"{th:.2f}", EVENTS.get(f"{m:%Y-%m}", ""))
                for m, p, th in zip(f["month"], f["psi"], f["threshold"])]

    report = "\n\n".join([
        "# Retune rules replayed on 2019-2026",
        f"Generated by `ops/replay_triggers.py` from the public app's snapshot (measured days through "
        f"{daily['date'].max():%Y-%m-%d}). The replay refits the production settings every Monday from "
        f"{START} ({replay['trained_through'].nunique()} fits) and forecasts the next 90 days, the way production "
        "does, so its errors are what live errors would have been. See `databricks/src/parks_lib/monitoring.py` "
        "for the rules.",
        "## Error trigger",
        f"Fires when the 28-day error of forecasts made 0-14 days ahead stays above the band (the "
        f"{mon.BAND_QUANTILES[1]:.0%} point of the replay's 28-day errors over the two years ending 90 days "
        f"earlier) for {mon.SUSTAIN_DAYS} days in a row.",
        table([(f"{d:%Y-%m-%d}", EVENTS.get(f"{d:%Y-%m}", "") or EVENTS.get(f"{d - pd.Timedelta(days=28):%Y-%m}", ""))
               for d in fires], ["Would have fired", "What was going on"]),
        "By year (28-day error and band, averaged over the year's days; share of days above the band):",
        table([(y, f"{r.error:.1f}", f"{r.band:.1f}", f"{r.above:.0%}", int(fires_by_year.get(y, 0)))
               for y, r in by_year.iterrows()], ["Year", "28-day error", "Band top", "Days above", "Fires"]),
        "## Drift by month",
        f"Model errors: flagged in {len(flagged(errors))} of {len(errors)} months (median threshold "
        f"{errors['threshold'].median():.2f}; the textbook line is 0.2). Only this line can start a retune.",
        table(flagged(errors), ["Month", "PSI", "Threshold", "What was going on"]),
        f"Crowd level against the same month in the three years before: flagged in {len(flagged(crowd))} of "
        f"{len(crowd)} months (median threshold {crowd['threshold'].median():.2f}). Information only: crowds "
        "shifting while the model's errors hold steady is the weekly retrain doing its job.",
        table(flagged(crowd), ["Month", "PSI", "Threshold", "What was going on"]),
    ]) + "\n"
    OUT.write_bytes(report.encode("utf-8"))
    print(report)


if __name__ == "__main__":
    main()
